const stored = (() => { try { return localStorage.getItem('dsp_lang') || 'ru' } catch { return 'ru' } })()
export const lang = writable(stored)
lang.subscribe(v => { try { localStorage.setItem('dsp_lang', v) } catch {} })

export function toggleLang() { lang.update(l => l === 'ru' ? 'en' : 'ru') }

